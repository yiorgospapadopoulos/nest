"""Pixel-art pixie mascots: read `design/mascots.toml` and render the TypeScript and Swift files."""

import re
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

MASCOTS_FILE = Path("design") / "mascots.toml"
NAMES = (
    "bluebell",
    "dragonfly",
    "moth",
    "firefly",
    "rose",
    "frost",
    "sprig",
    "nightshade",
    "brook",
    "star",
)
COLUMNS = 14
ROWS = 14
MIN_FILLED = 30
# Cell codes: empty, body, shade, light, wing tint, eye, ink (B89).
CELLS = ".#+o*ek"
EYE = "e"
# The colour of "e" and "k" cells in both themes.
INK = "#221E29"


@dataclass(frozen=True)
class Tone:
    """A cell drawn as the pixie's colour mixed toward `toward` by `amount`, per RGB
    channel and rounded, at `opacity`.
    """

    toward: str
    amount: float
    opacity: float


# "+" shade, "o" light and "*" wing tint; "#" is the pixie's colour itself.
TONES = {
    "shade": Tone("#000000", 0.30, 1),
    "light": Tone("#FFFFFF", 0.70, 1),
    "wing": Tone("#FFFFFF", 0.45, 0.85),
}
_TONE_CELLS = {"shade": "+", "light": "o", "wing": "*"}

_COLOR = re.compile(r"^#[0-9A-Fa-f]{6}$")
_HEADER = "// Generated by `nestd design generate` from design/mascots.toml. Do not edit.\n"


@dataclass(frozen=True)
class Mascots:
    colors: tuple[str, ...]
    sprites: dict[str, tuple[str, ...]]


def _check_rows(name: str, value: object) -> tuple[str, ...]:
    if not isinstance(value, list) or len(cast(list[Any], value)) != ROWS:
        msg = f"mascot {name}: needs {ROWS} rows"
        raise ValueError(msg)
    rows = cast(list[Any], value)
    for number, row in enumerate(rows, start=1):
        if not isinstance(row, str) or len(row) != COLUMNS or not set(row) <= set(CELLS):
            msg = f"mascot {name}, row {number}: needs {COLUMNS} characters of {CELLS}"
            raise ValueError(msg)
    checked = tuple(cast(list[str], rows))
    if sum(len(row) - row.count(".") for row in checked) < MIN_FILLED:
        msg = f"mascot {name}: needs at least {MIN_FILLED} filled cells"
        raise ValueError(msg)
    if not any(EYE in row for row in checked):
        msg = f"mascot {name}: needs at least one eye ('{EYE}') cell"
        raise ValueError(msg)
    return checked


def load_mascots(path: Path) -> Mascots:
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        msg = f"{path}: not found"
        raise ValueError(msg) from error
    except tomllib.TOMLDecodeError as error:
        msg = f"{path}: invalid TOML: {error}"
        raise ValueError(msg) from error
    colors = data.get("colors", [])
    for color in colors:
        if not isinstance(color, str) or not _COLOR.match(color):
            msg = f"{path}: colour {color!r} is not #RRGGBB"
            raise ValueError(msg)
    tables = data.get("mascots", {})
    if list(tables) != list(NAMES):
        msg = f"{path}: mascots must be exactly {', '.join(NAMES)} in that order"
        raise ValueError(msg)
    sprites = {name: _check_rows(name, tables[name].get("rows")) for name in NAMES}
    return Mascots(colors=tuple(colors), sprites=sprites)


_GRID_DOC = (
    f"{COLUMNS} columns by {ROWS} rows; cell codes: "
    '"." empty, "#" body, "+" shade, "o" light, "*" wing tint, "e" eye, "k" ink.'
)
_INK_DOC = (
    'The colour of "e" and "k" cells in both themes; "e" cells are the body colour while blinking.'
)
_TONES_DOC = (
    'How "+" (shade), "o" (light) and "*" (wing) cells derive from the pixie\'s colour (B89).'
)


def _number(value: float) -> str:
    return f"{value:g}"


def render_ts(m: Mascots) -> str:
    sprites = "\n".join(
        f'  "{name}": [\n' + "".join(f'    "{row}",\n' for row in rows) + "  ],"
        for name, rows in m.sprites.items()
    )
    colors = "".join(f'  "{color}",\n' for color in m.colors)
    tones = "".join(
        f'  {name}: {{ toward: "{t.toward}", amount: {_number(t.amount)}, '
        f"opacity: {_number(t.opacity)} }},\n"
        for name, t in TONES.items()
    )
    return (
        f"{_HEADER}\n"
        'import type { Mascot } from "../api/types.ts";\n\n'
        f"/** {_GRID_DOC} */\n"
        f"export const MASCOT_SPRITES: Record<Mascot, readonly string[]> = {{\n{sprites}\n}};\n\n"
        f"/** {_INK_DOC} */\n"
        f'export const MASCOT_INK = "{INK}";\n\n'
        f"/** {_TONES_DOC} */\n"
        f"export const MASCOT_TONES = {{\n{tones}}} as const;\n\n"
        f"export const PIXIE_COLORS: readonly string[] = [\n{colors}];\n"
    )


def render_swift(m: Mascots) -> str:
    sprites = "\n".join(
        f'        "{name}": [\n' + "".join(f'            "{row}",\n' for row in rows) + "        ],"
        for name, rows in m.sprites.items()
    )
    colors = "".join(f'        "{color}",\n' for color in m.colors)
    tones = "".join(
        f'    /// "{_TONE_CELLS[name]}" cells.\n'
        f'    public static let {name} = MascotTone(toward: "{t.toward}", '
        f"amount: {_number(t.amount)}, opacity: {_number(t.opacity)})\n"
        for name, t in TONES.items()
    )
    return (
        f"{_HEADER}\n"
        "import Foundation\n\n"
        f"/// {_GRID_DOC}\n"
        "public enum MascotSprites {\n"
        f"    public static let rows: [String: [String]] = [\n{sprites}\n    ]\n"
        "}\n\n"
        "/// A cell's colour: the pixie's colour mixed toward `toward` by `amount`, per RGB\n"
        "/// channel and rounded, drawn at `opacity`.\n"
        "public struct MascotTone: Sendable, Equatable {\n"
        "    public let toward: String\n"
        "    public let amount: Double\n"
        "    public let opacity: Double\n"
        "}\n\n"
        f"/// {_TONES_DOC}\n"
        "public enum MascotTones {\n"
        f"    /// {_INK_DOC}\n"
        f'    public static let ink = "{INK}"\n'
        f"{tones}"
        "}\n\n"
        "public enum PixieColors {\n"
        f"    public static let presets: [String] = [\n{colors}    ]\n"
        "}\n"
    )
